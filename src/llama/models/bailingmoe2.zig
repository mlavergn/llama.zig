//! Bailing MoE 2 (Ling 2.0): pre-norm blocks with a fused QKV projection
//! and Q and K norms, leading dense blocks, then a mixture of experts with
//! a selection bias and shared experts. NextN/MTP blocks past the main stack
//! are kept in the file but neither loaded nor run.
//!
//! # Provenance
//!
//! Ported from `llama.cpp/src/models/bailingmoe2.cpp` at v0.4.0
//! (`5266f24da`): `llama_model_bailingmoe2`'s `load_arch_hparams`,
//! `load_arch_tensors` and `build_arch_graph`, and its `graph`.

