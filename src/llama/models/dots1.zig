//! dots.llm1: pre-norm blocks with Q and K norms, leading dense blocks,
//! then a mixture of experts with a selection bias and a shared expert.
//!
//! # Provenance
//!
//! Ported from `llama.cpp/src/models/dots1.cpp` at v0.4.1 (`b29c606e2`):
//! `llama_model_dots1`'s `load_arch_hparams`, `load_arch_tensors` and
//! `build_arch_graph`, and its `graph`.

