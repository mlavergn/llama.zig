/// `create_memory`'s `reuse` for Gemma 3n and Gemma 4 (llama-model.cpp:2499
/// @c1d0e7a00): the layers from `n_layer_kv_from_start` on read the cells of
/// the last full or the last SWA layer before it.
fn reuseKvFromStart(ctx: ?*const anyopaque, il_: i32) i32 {
    const hp = hpOf(ctx);
    impl.assert(hp.n_layer_kv_from_start >= 2, "llama-model.cpp", 2500, "hparams.n_layer_kv_from_start >= 2");
    const il: u32 = @bitCast(il_);
    if (il >= @as(u32, @bitCast(hp.n_layer_kv_from_start))) {
        return hp.n_layer_kv_from_start - @as(i32, if (hp.isSwa(il)) 2 else 1);
    }
    return -1;
}

/// `create_memory`'s `share` for the Gemma 4 assistant (llama-model.cpp:2530
/// @c1d0e7a00): its SWA layers read the target's last SWA layer, the others
/// its last layer. The C++ asks `llama_model_n_layer` of the target on every
/// call; the answer does not change, so it is taken once.
const ShareFromOther = struct {
    hparams: *const Hparams,
    n_layer_other: i32,

    fn call(ctx: ?*const anyopaque, il: i32) i32 {
        const self: *const ShareFromOther = @ptrCast(@alignCast(ctx.?));
        if (self.hparams.isSwa(@bitCast(il))) return self.n_layer_other - 2;
        return self.n_layer_other - 1;
    }
};

