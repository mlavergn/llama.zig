                // MoE expert weight scales, one per expert.
                if (layer.ffn_gate_exps_s == null and layer.ffn_gate_exps != null) layer.ffn_gate_exps_s = try self.createTensor(.{ .tensor = .ffn_gate_exps, .suffix = "scale", .bid = i }, &nexp, nr, exc);
