    /// Ports `llama_model`'s `create_memory` (llama-model.cpp:2188 @c1d0e7a00),
    /// its default arm -- a recurrent memory, a hybrid one, or a KV cache --
    /// the encoders' arm, MiniMax-M3's MSA cache, the DSA and DSA-iSWA arms
    /// of GLM-DSA, DeepSeek V3.2 and dots.llm3, and DeepSeek V4's DSV4 cache.
    ///
    /// Return: the memory, or null for a model without one; `error.Thrown`.
    pub fn createMemory(self: *const Model, params: *const memory_mod.Params, cparams: *const cparams_mod.Cparams, exc: *Exception) Thrown!?memory_mod.Memory {
        const hp = &self.hparams;
        const a = self.arch;
        // Dense MTP heads use a plain attention KV cache.
        const mtp_on_hybrid_qwen = params.ctx_type == c.LLAMA_CONTEXT_TYPE_MTP and (a == .qwen3next or a == .qwen35 or a == .qwen35moe or a == .bailingmoe3);
        const mtp_on_hybrid_nemotron = params.ctx_type == c.LLAMA_CONTEXT_TYPE_MTP and a == .nemotron_h_moe;
        const swa_type: hparams_mod.SwaType = @fromBackingInt(@intCast(hp.swa_type));

        // The encoders, embedding models and diffusion models attend within
        // the batch and keep nothing between decodes.
        switch (a) {
            .bert, .jina_bert_v2, .jina_bert_v3, .nomic_bert, .nomic_bert_moe, .neo_bert, .eurobert, .wavtokenizer_dec, .modern_bert, .gemma_embedding, .dream, .llada, .llada_moe, .rnd1 => return null,
            .minimax_m3 => {
                // The sparse (MSA) layers carry an indexer key cache; the
                // leading dense layers do not.
                const filter_idx: memory_mod.LayerFilter = .{ .ctx = hp, .func = filterMsaIdx };

                const m = try kv_cache_msa.KvCacheMsa.create(self, params.type_k, params.type_v, !cparams.flash_attn, cparams.offload_kqv, cparams.kv_unified, cparams.n_ctx_seq, cparams.n_seq_max, 1, hp.n_swa, swa_type, .{}, filter_idx, .{}, exc);
                return m.memoryOf();
            },
            .glm_dsa, .deepseek32 => {
                if (params.ctx_type == c.LLAMA_CONTEXT_TYPE_MTP and hp.n_layer_nextn > 0) {
                    // The NextN/MTP draft head runs dense MLA, without the
                    // DSA indexer, so the MTP context has a plain attention
                    // KV cache of the nextn layers alone -- as the hybrid
                    // Qwen3.5's MTP context does.
                    const filter: memory_mod.LayerFilter = .{ .ctx = hp, .func = filterNextn };
                    const m = try kv_cache.KvCache.create(self, hp, params.type_k, params.type_v, !cparams.flash_attn, cparams.offload_kqv, cparams.kv_unified, cparams.n_ctx_seq, cparams.n_seq_max, 1, hp.n_swa, swa_type, null, filter, .{}, .{}, exc);
                    return m.memoryOf();
                }
                // The main context: a DSA cache for the trunk layers alone,
                // which never attend the nextn layers.
                var filter_mla: memory_mod.LayerFilter = .{};
                if (hp.n_layer_nextn > 0) filter_mla = .{ .ctx = hp, .func = filterTrunk };
                const filter_lid: memory_mod.LayerFilter = .{ .ctx = self, .func = filterLidDsa };
                const m = try kv_cache_dsa.KvCacheDsa.create(self, params.type_k, params.type_v, !cparams.flash_attn, cparams.offload_kqv, cparams.kv_unified, cparams.n_ctx_seq, cparams.n_seq_max, 1, hp.n_swa, swa_type, filter_mla, filter_lid, .{}, exc);
                return m.memoryOf();
            },
            .dots3note => {
                impl.assert(swa_type != .none, "llama-model.cpp", 2288, "hparams.swa_type != LLAMA_SWA_TYPE_NONE");

                if (params.ctx_type == c.LLAMA_CONTEXT_TYPE_MTP and hp.n_layer_nextn > 0) {
                    // The MTP draft context: a plain attention KV cache of
                    // the nextn layer alone.
                    const filter: memory_mod.LayerFilter = .{ .ctx = hp, .func = filterNextn };
                    const m = try kv_cache.KvCache.create(self, hp, params.type_k, params.type_v, !cparams.flash_attn, cparams.offload_kqv, cparams.kv_unified, cparams.n_ctx_seq, cparams.n_seq_max, 1, hp.n_swa, swa_type, null, filter, .{}, .{}, exc);
                    return m.memoryOf();
                }
                // The main context: a DSA cache for the trunk's
                // full-attention layers and a window-sized SWA cache.
                var filter_mla: memory_mod.LayerFilter = .{};
                if (hp.n_layer_nextn > 0) filter_mla = .{ .ctx = hp, .func = filterTrunk };
                const filter_lid: memory_mod.LayerFilter = .{ .ctx = hp, .func = filterLidFull };
                const m = try kv_cache_dsa_iswa.KvCacheDsaIswa.create(self, params.type_k, params.type_v, !cparams.flash_attn, cparams.offload_kqv, params.swa_full, cparams.kv_unified, cparams.n_ctx_seq, cparams.n_seq_max, cparams.n_ubatch, 1, filter_mla, filter_lid, .{}, exc);
                return m.memoryOf();
            },
            // `LLM_ARCH_DEEPSEEK4` (llama-model.cpp:2337 @c1d0e7a00): an MTP draft
            // context holds only the nextn layers, in an iSWA cache its graph
            // reads K-only; the main context the DSV4 cache.
            .deepseek4 => {
                impl.assert(swa_type != .none, "llama-model.cpp", 2339, "hparams.swa_type != LLAMA_SWA_TYPE_NONE");

                if (params.ctx_type == c.LLAMA_CONTEXT_TYPE_MTP) {
                    const filter_mtp: memory_mod.LayerFilter = .{ .ctx = hp, .func = filterNextn };
                    const m = try kv_cache_iswa.KvCacheIswa.create(self, null, params.type_k, params.type_v, !cparams.flash_attn, cparams.offload_kqv, params.swa_full, cparams.kv_unified, cparams.n_ctx_seq, cparams.n_seq_max, cparams.n_ubatch, 1, null, filter_mtp, .{}, .{}, exc);
                    return m.memoryOf();
                }
                const m = try kv_cache_dsv4.KvCacheDsv4.create(self, params.type_k, params.type_v, !cparams.flash_attn, cparams.offload_kqv, params.swa_full, cparams.kv_unified, cparams.n_ctx_seq, cparams.n_seq_max, cparams.n_ubatch, 1, cparams.n_rs_seq, .{}, .{}, exc);
                return m.memoryOf();
            },
            // DeepSeek-V4's DSpark stages keep one MLA-style K per position,
            // their window the draft ring; any other DFlash falls through
            // to the default arm.
            .dflash => if (hp.dsv4_hc_mult > 0) {
                impl.assert(swa_type != .none, "llama-model.cpp", 2384, "hparams.swa_type != LLAMA_SWA_TYPE_NONE");
                const m = try kv_cache_iswa.KvCacheIswa.create(self, null, params.type_k, params.type_v, !cparams.flash_attn, cparams.offload_kqv, params.swa_full, cparams.kv_unified, cparams.n_ctx_seq, cparams.n_seq_max, cparams.n_ubatch, 1, null, .{}, .{}, .{}, exc);
                return m.memoryOf();
            },
            else => {},
        }

        if (arch.isRecurrent(a)) {
            const m = try memory_recurrent.MemoryRecurrent.create(self, c.GGML_TYPE_F32, c.GGML_TYPE_F32, cparams.offload_kqv, @max(1, cparams.n_seq_max), cparams.n_seq_max, cparams.n_rs_seq, .{}, exc);
            return m.memoryOf();
        }
        if (arch.isHybrid(a) and !mtp_on_hybrid_qwen and !mtp_on_hybrid_nemotron) {
            // Hybrid architectures differ mainly in their layer filters.
            var filter_attn: memory_mod.LayerFilter = .{};
            var filter_recr: memory_mod.LayerFilter = .{};
            if (a == .falcon_h1) {
                filter_attn = .{ .ctx = hp, .func = filterAll };
                filter_recr = .{ .ctx = hp, .func = filterAll };
            } else if (a == .nemotron_h or a == .nemotron_h_moe) {
                filter_attn = .{ .ctx = hp, .func = filterNemotronAttn };
                filter_recr = .{ .ctx = hp, .func = filterNemotronRecr };
            } else if (a == .qwen3next or a == .qwen35 or a == .qwen35moe or a == .minimax_01) {
                filter_attn = .{ .ctx = hp, .func = filterTrunkAttn };
                filter_recr = .{ .ctx = hp, .func = filterTrunkRecr };
            }
            if (swa_type != .none) {
                // Hybrid models with SWA use the hybrid iSWA memory.
                const m = try memory_hybrid_iswa.MemoryHybridIswa.create(self, params.type_k, params.type_v, !cparams.flash_attn, params.swa_full, cparams.n_ctx_seq, cparams.n_ubatch, 1, c.GGML_TYPE_F32, c.GGML_TYPE_F32, @max(1, cparams.n_seq_max), cparams.n_seq_max, cparams.n_rs_seq, cparams.offload_kqv, cparams.kv_unified, filter_attn, filter_recr, exc);
                return m.memoryOf();
            }
            const m = try memory_hybrid.MemoryHybrid.create(self, params.type_k, params.type_v, !cparams.flash_attn, cparams.n_ctx_seq, 1, hp.n_swa, swa_type, c.GGML_TYPE_F32, c.GGML_TYPE_F32, @max(1, cparams.n_seq_max), cparams.n_seq_max, cparams.n_rs_seq, cparams.offload_kqv, cparams.kv_unified, filter_attn, filter_recr, exc);
            return m.memoryOf();
        }

        var filter: memory_mod.LayerFilter = .{};
        var reuse: memory_mod.LayerMap = .{};
        var share: memory_mod.LayerMap = .{};

        if (a == .gemma3n or a == .gemma4) reuse = .{ .ctx = hp, .func = reuseKvFromStart };

        if (mtp_on_hybrid_qwen or mtp_on_hybrid_nemotron) filter = .{ .ctx = hp, .func = filterNextn };
        if ((a == .step35 or a == .hy_v3 or a == .glm_dsa or a == .mimo2 or a == .deepseek32) and hp.n_layer_nextn > 0) {
            filter = if (params.ctx_type == c.LLAMA_CONTEXT_TYPE_MTP) .{ .ctx = hp, .func = filterNextn } else .{ .ctx = hp, .func = filterTrunk };
        }
        if (swa_type != .none) {
            impl.assert(hp.isSwaAny(), "llama-model.cpp", 2525, "hparams.is_swa_any()");

            if (a == .gemma4_assistant) {
                // The assistant reads the target model's last full and last
                // SWA layers.
                const other: *const context_mod.Context = @ptrCast(@alignCast(cparams.ctx_other.?));
                const mem_other = other.getMemory();
                const share_ctx: ShareFromOther = .{ .hparams = hp, .n_layer_other = @intCast(other.getModel().hparams.nLayer()) };
                share = .{ .ctx = &share_ctx, .func = ShareFromOther.call };
                const m = try kv_cache_iswa.KvCacheIswa.create(self, null, params.type_k, params.type_v, !cparams.flash_attn, cparams.offload_kqv, params.swa_full, cparams.kv_unified, cparams.n_ctx_seq, cparams.n_seq_max, cparams.n_ubatch, 1, mem_other, filter, reuse, share, exc);
                return m.memoryOf();
            }
            const m = try kv_cache_iswa.KvCacheIswa.create(self, null, params.type_k, params.type_v, !cparams.flash_attn, cparams.offload_kqv, params.swa_full, cparams.kv_unified, cparams.n_ctx_seq, cparams.n_seq_max, cparams.n_ubatch, 1, null, filter, reuse, share, exc);
            return m.memoryOf();
        }
        impl.assert(!hp.isSwaAny(), "llama-model.cpp", 2575, "!hparams.is_swa_any()");
        const mem_other: ?*kv_cache.KvCache = null;
        const m = try kv_cache.KvCache.create(self, hp, params.type_k, params.type_v, !cparams.flash_attn, cparams.offload_kqv, cparams.kv_unified, cparams.n_ctx_seq, cparams.n_seq_max, 1, hp.n_swa, swa_type, mem_other, filter, reuse, share, exc);
        return m.memoryOf();
    }

    /// Ports `llama_model`'s `build_graph` (llama-model.cpp:2602 @c1d0e7a00):
    /// the architecture's graph, then pooling, backend sampling and the dense
    /// projections.
