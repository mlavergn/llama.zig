//! Build-time tool: the `ui_assets` module `tools/server/ui.zig` reads, from
//! a built web UI.
//!
//! Not a port of a file. It does for the port what upstream's
//! `scripts/ui-assets.cmake` (`emit_files`) does for `ui.cpp`, and what
//! `llama.cpp.zmake/zig/ui_embed.zig` does for the reference built here:
//! every file under the dist directory, `_gzip/` excluded, sorted by name;
//! none when there is no `index.html`; the required-asset check; with gzip
//! on, each file gzip-compressed with a zero timestamp by the same
//! compressor and level `ui_embed.zig` uses, so the two embed the same bytes
//! and the same ETags (the quoted SHA-256 of the embedded bytes); the same
//! MIME table. `server-diff`'s `ui` cases compare what the two serve.
//!
//! Usage:
//!   ui_assets <dist-dir | -> <gzip: 0|1> <out-dir>
//!
//! Writes `<out-dir>/assets.zig` and one `<out-dir>/a<N>.bin` per asset.

const std = @import("std");
const flate = std.compress.flate;

/// Entry point.
///
/// Parameters:
/// - `init`: process capabilities supplied by the runtime (allocator, IO, args).
///
/// Return: nothing on success; `error.BadUsage`, `error.MissingAssets`,
/// `error.EmptyAsset`, and read, write and allocation failures otherwise.
pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 4) return error.BadUsage;

    const want_gzip = std.mem.eql(u8, args[2], "1");
    const cwd = std.Io.Dir.cwd();
    var out = try cwd.openDir(io, args[3], .{});
    defer out.close(io);
    const limit: std.Io.Limit = .limited(256 << 20);

    var names: std.ArrayList([]const u8) = .empty;
    var dist: ?std.Io.Dir = null;
    defer if (dist) |*d| d.close(io);
    if (!std.mem.eql(u8, args[1], "-")) {
        dist = try cwd.openDir(io, args[1], .{ .iterate = true });
        const has_index = if (dist.?.access(io, "index.html", .{})) true else |_| false;
        if (has_index) {
            var walker = try dist.?.walk(arena);
            defer walker.deinit();
            while (try walker.next(io)) |entry| {
                if (entry.kind == .directory) continue;
                const rel = try arena.dupe(u8, entry.path);
                std.mem.replaceScalar(u8, rel, std.fs.path.sep, '/');
                if (std.mem.startsWith(u8, rel, "_gzip/")) continue;
                try names.append(arena, rel);
            }
            std.mem.sort([]const u8, names.items, {}, lessThan);
        }
    }
    try validate(names.items);
    const use_gzip = want_gzip and names.items.len > 0;

    var src: std.Io.Writer.Allocating = .init(arena);
    const w = &src.writer;
    try w.writeAll(
        \\//! Generated by build/ui_assets.zig from the built web UI -- do not edit.
        \\
        \\/// `llama_ui_asset`: one embedded file.
        \\pub const Asset = struct {
        \\    name: []const u8,
        \\    data: []const u8,
        \\    etag: []const u8,
        \\    type: []const u8,
        \\};
        \\
        \\
    );
    try w.print("pub const use_gzip = {};\n\n", .{use_gzip});
    try w.print("pub const assets = [{d}]Asset{{\n", .{names.items.len});
    for (names.items, 0..) |name, idx| {
        const raw = try dist.?.readFileAlloc(io, name, arena, limit);
        const data = if (use_gzip) try gzip(arena, raw) else raw;
        if (data.len == 0) {
            std.log.err("UI: empty file: {s}/{s}", .{ args[1], name });
            return error.EmptyAsset;
        }
        const file = try std.fmt.allocPrint(arena, "a{d}.bin", .{idx});
        try out.writeFile(io, .{ .sub_path = file, .data = data });

        var digest: [32]u8 = undefined;
        std.crypto.hash.sha2.Sha256.hash(data, &digest, .{});
        const etag = std.fmt.bytesToHex(digest, .lower);
        try w.print("    .{{ .name = \"{f}\", .data = @embedFile(\"{s}\"), .etag = \"\\\"{s}\\\"\", .type = \"{s}\" }},\n", .{
            std.zig.fmtString(name), file, &etag, mimeFromExt(name),
        });
    }
    try w.writeAll("};\n");
    try out.writeFile(io, .{ .sub_path = "assets.zig", .data = src.written() });
}

/// Byte order, as CMake's `list(SORT)`.
fn lessThan(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.lessThan(u8, a, b);
}

/// `ui_validate_assets`: a non-empty bundle must hold every file the UI
/// loads at run time.
fn validate(names: []const []const u8) !void {
    if (names.len == 0) return;
    const labels = [_][]const u8{ "index.html", "manifest.webmanifest", "sw.js", "build.json", "version.json", "bundle[hash].js", "bundle[hash].css", "workbox[hash].js" };
    var found: [labels.len]bool = @splat(false);
    for (names) |name| {
        const base = std.fs.path.basenamePosix(name);
        for (labels[0..5], 0..) |l, i| if (std.mem.eql(u8, base, l)) {
            found[i] = true;
        };
        if (std.mem.startsWith(u8, base, "bundle") and std.mem.endsWith(u8, base, ".js")) found[5] = true;
        if (std.mem.startsWith(u8, base, "bundle") and std.mem.endsWith(u8, base, ".css")) found[6] = true;
        if (std.mem.startsWith(u8, base, "workbox") and std.mem.endsWith(u8, base, ".js")) found[7] = true;
    }
    var missing = false;
    for (labels, found) |l, f| if (!f) {
        std.log.err("UI: missing required asset: {s}", .{l});
        missing = true;
    };
    if (missing) return error.MissingAssets;
}

/// gzip, zero timestamp, the default level: `ui_embed.zig`'s exactly.
fn gzip(a: std.mem.Allocator, raw: []const u8) ![]u8 {
    var out: std.Io.Writer.Allocating = try .initCapacity(a, raw.len / 2 + 64);
    const window = try a.alloc(u8, flate.max_window_len);
    var c: flate.Compress = try .init(&out.writer, window, .gzip, .default);
    try c.writer.writeAll(raw);
    try c.finish();
    return out.toOwnedSlice();
}

/// `mime_from_ext`.
fn mimeFromExt(name: []const u8) []const u8 {
    const dot = std.mem.lastIndexOfScalar(u8, name, '.') orelse return "application/octet-stream";
    const ext = name[dot + 1 ..];
    const table = [_][2][]const u8{
        .{ "html", "text/html; charset=utf-8" },
        .{ "css", "text/css" },
        .{ "js", "application/javascript" },
        .{ "json", "application/json" },
        .{ "webmanifest", "application/manifest+json" },
        .{ "svg", "image/svg+xml" },
        .{ "png", "image/png" },
        .{ "jpg", "image/jpeg" },
        .{ "jpeg", "image/jpeg" },
        .{ "ico", "image/x-icon" },
        .{ "woff", "font/woff" },
        .{ "woff2", "font/woff2" },
    };
    for (table) |row| if (std.mem.eql(u8, ext, row[0])) return row[1];
    return "application/octet-stream";
}
