//! Build file for `mtmd_audio_diff`, the gate for
//! `src/mtmd/audio.zig` against upstream's `tools/mtmd/mtmd-audio.cpp`.
//!
//! The reference is `mtmd-audio.cpp` compiled unmodified here with the flags
//! `libmtmd-ref` compiles it with (`build/tools.zig`, `cxx_flags`), beside
//! `harness/mtmd_audio_ref.cpp`, which supplies its logger, and upstream's
//! own `mtmd_audio_log_mel` (and the `static` helper it calls), cut out of
//! `mtmd-subcontext.cpp` at configure time (`logMelSource`), so the rest of
//! libmtmd stays out of the link.
//!
//! **Not a port.** This is build description.

const std = @import("std");
const mtmd = @import("mtmd.zig");
const llamacpp = @import("llamacpp.zig");

const root = "llama.cpp";

/// `build/tools.zig`'s `cxx_flags`: what `libmtmd-ref` compiles with.
const cxx_flags = [_][]const u8{ "-std=c++17", "-w" };

/// Adds `mtmd-audio-diff`.
pub fn add(b: *std.Build, opts: mtmd.GateOptions) void {
    const mod = b.createModule(.{
        .root_source_file = b.path("harness/mtmd_audio_diff.zig"),
        .target = opts.target,
        .optimize = opts.optimize,
        .link_libc = true,
        .link_libcpp = true,
        // Reference code compiles as shipped; see `addLlamaRef`.
        .sanitize_c = .off,
    });
    // The port, rooted at `src/mtmd/audio.zig` itself rather than the whole
    // `mtmd` module: it reaches only `impl.zig`, `model.zig` and `names.zig`
    // beside it, so this gate builds whatever state the rest of libmtmd is in.
    const audio_mod = b.createModule(.{
        .root_source_file = b.path("src/mtmd/audio.zig"),
        .target = opts.target,
        .optimize = opts.optimize,
        .link_libc = true,
    });
    audio_mod.addImport("llama", opts.reference.llama.root_module);
    mod.addImport("mtmd_audio", audio_mod);
    for ([_][]const u8{ "", "/include", "/common", "/ggml/include", "/ggml/src", "/vendor", "/tools/mtmd" }) |sub| {
        mod.addIncludePath(b.path(b.fmt("{s}{s}", .{ root, sub })));
    }
    mod.addCSourceFiles(.{ .root = b.path(root), .files = &.{"tools/mtmd/mtmd-audio.cpp"}, .flags = &cxx_flags });
    mod.addCSourceFiles(.{ .files = &.{"harness/mtmd_audio_ref.cpp"}, .flags = &cxx_flags });
    const wf = b.addWriteFiles();
    mod.addCSourceFile(.{ .file = wf.add("mtmd_audio_log_mel_ref.cpp", logMelSource(b)), .flags = &cxx_flags });
    mod.linkLibrary(opts.reference.ggml);
    llamacpp.addSdkPaths(b, mod, opts.sdk);
    llamacpp.addCudaRuntime(b, mod, opts.cuda);

    const exe = b.addExecutable(.{ .name = "mtmd-audio-diff", .root_module = mod });
    const install = b.addInstallArtifact(exe, .{});
    const step = b.step("mtmd-audio-diff", "Build the mtmd audio preprocessing gate (scripts/mtmd-audio-diff runs it)");
    step.dependOn(&install.step);
}

/// Upstream's `mtmd_backend_cpu_set_n_threads` and `mtmd_audio_log_mel`,
/// verbatim, cut out of `tools/mtmd/mtmd-subcontext.cpp`: each runs from its
/// first line to the next line that is a lone `}`. Compiling the whole file
/// would drag every encoder graph into the link.
fn logMelSource(b: *std.Build) []const u8 {
    const path = root ++ "/tools/mtmd/mtmd-subcontext.cpp";
    // A failure here must break this gate's build alone, not every `zig
    // build`: it becomes an `#error` in the generated file.
    const text = std.Io.Dir.cwd().readFileAlloc(b.graph.io, path, b.allocator, .unlimited) catch
        return "#error \"mtmd-audio-diff: cannot read tools/mtmd/mtmd-subcontext.cpp\"\n";
    var out: std.ArrayList(u8) = .empty;
    out.appendSlice(b.allocator,
        \\// Generated by build/mtmd_audio_diff.zig from upstream's
        \\// tools/mtmd/mtmd-subcontext.cpp -- do not edit.
        \\#include "mtmd-subcontext.h"
        \\#include "mtmd-audio.h"
        \\#include <algorithm>
        \\#include <cfloat>
        \\#include <cmath>
        \\
        \\
    ) catch @panic("OOM");
    for ([_][]const u8{ "static void mtmd_backend_cpu_set_n_threads(", "bool mtmd_audio_log_mel(" }) |head| {
        const start = std.mem.indexOf(u8, text, head) orelse
            return b.fmt("#error \"mtmd-audio-diff: `{s}` not found in mtmd-subcontext.cpp\"\n", .{head});
        const end = std.mem.indexOfPos(u8, text, start, "\n}\n") orelse
            return b.fmt("#error \"mtmd-audio-diff: no end for `{s}`\"\n", .{head});
        out.appendSlice(b.allocator, text[start .. end + 3]) catch @panic("OOM");
        out.appendSlice(b.allocator, "\n") catch @panic("OOM");
    }
    return out.items;
}
