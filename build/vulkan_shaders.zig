//! Build-time tool: turns the `.cpp` files upstream's `vulkan-shaders-gen`
//! writes into the shader table the Zig Vulkan host layer embeds. Not a port
//! of anything, and nothing of it ships.
//!
//! Each generated `.cpp` holds, for every variant of one shader file,
//! `const uint64_t NAME_len = N;` and `const unsigned char NAME_data[N] = {
//! 0x.., ... };`, then the dispatch tables over them --
//! `const void * add_data[2][2][2] = {{{add_f32_f32_f32_data, ...}}};` and
//! their `_len` twins. The reference compiles those files as C++; this reads
//! the same files, so the port's SPIR-V is the reference's byte for byte
//! (PLAN.md, Decisions 55 and 59 -- two runs of the generator are *not* the
//! same reference: `glslc -O` is not reproducible on `tri_f16`).
//!
//! Output: one blob of every variant's bytes, each starting at a multiple of
//! four, and a Zig file that slices it under the C names: `abs_f16_data` is
//! a `[]const u8`, `add_data` a `[2][2][2][]const u8`. The `_len` symbols are
//! not emitted; a slice carries its length.
//!
//! Usage: vulkan_shaders <out.zig> <out.bin> <generated.cpp>...

const std = @import("std");

const Variant = struct {
    name: []const u8,
    offset: usize,
    len: usize,
};

const Table = struct {
    name: []const u8,
    dims: []const usize,
    /// Element names in row-major order, each a `*_data` variant.
    items: []const []const u8,
};

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const arena = init.arena.allocator();
    const args = try init.minimal.args.toSlice(arena);
    if (args.len < 3) {
        std.debug.print("usage: vulkan_shaders <out.zig> <out.bin> <generated.cpp>...\n", .{});
        std.process.exit(2);
    }

    var blob: std.ArrayList(u8) = .empty;
    var variants: std.ArrayList(Variant) = .empty;
    var tables: std.ArrayList(Table) = .empty;

    const cwd = std.Io.Dir.cwd();
    for (args[3..]) |path| {
        const text = try cwd.readFileAlloc(io, path, arena, .unlimited);
        try parseFile(arena, path, text, &blob, &variants, &tables);
    }

    // Sorted by name, so the output does not depend on argument order.
    std.mem.sort(Variant, variants.items, {}, struct {
        fn lt(_: void, l: Variant, r: Variant) bool {
            return std.mem.lessThan(u8, l.name, r.name);
        }
    }.lt);
    std.mem.sort(Table, tables.items, {}, struct {
        fn lt(_: void, l: Table, r: Table) bool {
            return std.mem.lessThan(u8, l.name, r.name);
        }
    }.lt);

    var known: std.StringHashMapUnmanaged(void) = .empty;
    for (variants.items, 0..) |v, i| {
        if (i > 0 and std.mem.eql(u8, variants.items[i - 1].name, v.name)) fail("duplicate variant {s}", .{v.name});
        try known.put(arena, v.name, {});
    }
    for (tables.items) |t| for (t.items) |item| {
        if (!known.contains(item)) fail("table {s} names {s}, which no file defines", .{ t.name, item });
    };

    var out: std.Io.Writer.Allocating = .init(arena);
    const w = &out.writer;
    try w.writeAll(
        \\//! Generated by build/vulkan_shaders.zig from vulkan-shaders-gen's output.
        \\//! Do not edit. Every variant is a slice of one embedded blob, under its
        \\//! C name; every dispatch table is an array of those slices.
        \\
        \\const blob = @embedFile("vulkan_shaders_blob");
        \\
        \\
    );
    try w.print("/// Number of SPIR-V variants in the table.\npub const variant_count = {d};\n\n", .{variants.items.len});
    for (variants.items) |v| {
        try w.print("pub const {s}: []const u8 = blob[{d}..{d}];\n", .{ v.name, v.offset, v.offset + v.len });
    }
    try w.writeAll("\n");
    for (tables.items) |t| {
        try w.print("pub const {s}: ", .{t.name});
        for (t.dims) |d| try w.print("[{d}]", .{d});
        try w.writeAll("[]const u8 = ");
        var index: usize = 0;
        try writeLevel(w, t, 0, &index);
        try w.writeAll(";\n");
    }

    try cwd.writeFile(io, .{ .sub_path = args[1], .data = out.written() });
    try cwd.writeFile(io, .{ .sub_path = args[2], .data = blob.items });
}

fn writeLevel(w: *std.Io.Writer, t: Table, level: usize, index: *usize) !void {
    try w.writeAll(".{ ");
    for (0..t.dims[level]) |i| {
        if (i > 0) try w.writeAll(", ");
        if (level + 1 == t.dims.len) {
            try w.writeAll(t.items[index.*]);
            index.* += 1;
        } else {
            try writeLevel(w, t, level + 1, index);
        }
    }
    try w.writeAll(" }");
}

fn parseFile(
    arena: std.mem.Allocator,
    path: []const u8,
    text: []const u8,
    blob: *std.ArrayList(u8),
    variants: *std.ArrayList(Variant),
    tables: *std.ArrayList(Table),
) !void {
    const data_prefix = "const unsigned char ";
    const table_prefix = "const void * ";
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |line| {
        if (std.mem.startsWith(u8, line, data_prefix)) {
            // const unsigned char NAME_data[N] = {
            const rest = line[data_prefix.len..];
            const lb = std.mem.indexOfScalar(u8, rest, '[') orelse fail("{s}: bad data line", .{path});
            const rb = std.mem.indexOfScalarPos(u8, rest, lb, ']') orelse fail("{s}: bad data line", .{path});
            const name = rest[0..lb];
            const n = try std.fmt.parseInt(usize, rest[lb + 1 .. rb], 10);
            while (blob.items.len % 4 != 0) try blob.append(arena, 0);
            const offset = blob.items.len;
            while (blob.items.len - offset < n) {
                const hex_line = lines.next() orelse fail("{s}: {s} ends early", .{ path, name });
                var it = std.mem.tokenizeAny(u8, hex_line, ", \r");
                while (it.next()) |tok| {
                    if (std.mem.eql(u8, tok, "};")) fail("{s}: {s} is short", .{ path, name });
                    try blob.append(arena, try std.fmt.parseInt(u8, tok, 0));
                }
            }
            if (blob.items.len - offset != n) fail("{s}: {s} overruns its length", .{ path, name });
            try variants.append(arena, .{ .name = name, .offset = offset, .len = n });
        } else if (std.mem.startsWith(u8, line, table_prefix)) {
            // const void * NAME_data[a][b] = {{x_data, y_data, }, ...};
            const rest = line[table_prefix.len..];
            const lb = std.mem.indexOfScalar(u8, rest, '[') orelse fail("{s}: bad table line", .{path});
            const eq = std.mem.indexOf(u8, rest, "=") orelse fail("{s}: bad table line", .{path});
            var dims: std.ArrayList(usize) = .empty;
            var dit = std.mem.tokenizeAny(u8, rest[lb..eq], "[] ");
            while (dit.next()) |d| try dims.append(arena, try std.fmt.parseInt(usize, d, 10));
            var items: std.ArrayList([]const u8) = .empty;
            var iit = std.mem.tokenizeAny(u8, rest[eq + 1 ..], "{}, ;");
            while (iit.next()) |item| try items.append(arena, item);
            var total: usize = 1;
            for (dims.items) |d| total *= d;
            if (items.items.len != total) fail("{s}: table {s} has {d} items for {d} slots", .{ path, rest[0..lb], items.items.len, total });
            try tables.append(arena, .{ .name = rest[0..lb], .dims = dims.items, .items = items.items });
        }
    }
}

fn fail(comptime fmt: []const u8, args: anytype) noreturn {
    std.debug.print("vulkan_shaders: " ++ fmt ++ "\n", args);
    std.process.exit(1);
}
