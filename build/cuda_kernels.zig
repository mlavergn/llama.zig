//! Build-time tool that writes the CUDA kernel table, `cuda_kernels.zig`.
//!
//! **Not a port.** PLAN.md Decisions 44 and 45: every upstream `.cu` is
//! compiled to a fatbin and embedded; the Zig host layer names a kernel by
//! the translation unit it lives in and its demangled template spelling,
//! `mul_mat_q<(ggml_type)12, (int)64, (bool)0>`, and this table turns that
//! into the mangled symbol `cuLibraryGetKernel` wants. A key the table lacks
//! is a compile error in `src/ggml/cuda/kernels.zig`.
//!
//! The input for each translation unit is a symbol listing, one kernel per
//! line, `<mangled>\t<demangled>`, which `build/llamacpp.zig` makes with
//! `cuobjdump -symbols` and `cu++filt`. The key is the demangled text with
//! the return type and the parameter list removed: kernels return `void`,
//! and the parameter list adds nothing the template arguments do not
//! already say.
//!
//! Usage:
//!   cuda_kernels <out.zig> (<library> <symbols.txt>)...
//!
//! The generated module embeds each fatbin through an anonymous import named
//! `cuda_fatbin_<index>`, which `build/llamacpp.zig` adds in the same order.

const std = @import("std");

const Entry = struct {
    key: []const u8,
    mangled: []const u8,

    fn lessThan(_: void, l: Entry, r: Entry) bool {
        return std.mem.lessThan(u8, l.key, r.key);
    }
};

/// Entry point: reads every listing and writes the table.
///
/// Parameters:
/// - `init`: process capabilities supplied by the runtime (allocator, IO, args).
///
/// Return: nothing on success; propagates read, write and allocation
/// failures; `error.BadUsage` for an odd argument count and
/// `error.DuplicateKernel` when two different kernels of one library share a
/// key, which would make the key ambiguous.
pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(arena);
    if (args.len < 2 or (args.len - 2) % 2 != 0) return error.BadUsage;
    const cwd = std.Io.Dir.cwd();

    var out: std.ArrayList(u8) = .empty;
    try out.appendSlice(arena,
        \\//! Generated by `build/cuda_kernels.zig` from the entry symbols of every
        \\//! CUDA fatbin. **Not a port, and not to be edited.** See that file.
        \\
        \\pub const Entry = struct { key: []const u8, mangled: [:0]const u8 };
        \\
        \\pub const Library = struct {
        \\    name: []const u8,
        \\    fatbin: []const u8,
        \\    /// Index of this library's first kernel in the process-wide
        \\    /// kernel cache.
        \\    first: u32,
        \\    /// Sorted by `key`.
        \\    entries: []const Entry,
        \\};
        \\
        \\pub const libraries = [_]Library{
        \\
    );

    var first: u32 = 0;
    var i: usize = 2;
    var lib_index: usize = 0;
    while (i < args.len) : ({
        i += 2;
        lib_index += 1;
    }) {
        const name = args[i];
        const listing = try cwd.readFileAlloc(io, args[i + 1], arena, .limited(256 << 20));

        var entries: std.ArrayList(Entry) = .empty;
        var lines = std.mem.splitScalar(u8, listing, '\n');
        while (lines.next()) |line| {
            if (line.len == 0) continue;
            const tab = std.mem.findScalar(u8, line, '\t') orelse return error.BadListing;
            try entries.append(arena, .{
                .mangled = line[0..tab],
                .key = try keyOf(line[tab + 1 ..]),
            });
        }
        std.mem.sort(Entry, entries.items, {}, Entry.lessThan);
        for (entries.items[0..entries.items.len -| 1], entries.items[@min(1, entries.items.len)..]) |a, b| {
            if (std.mem.eql(u8, a.key, b.key)) {
                std.debug.print("cuda_kernels: {s}: two kernels share the key {s}:\n  {s}\n  {s}\n", .{ name, a.key, a.mangled, b.mangled });
                return error.DuplicateKernel;
            }
        }

        try out.print(arena, "    .{{ .name = \"{s}\", .fatbin = @embedFile(\"cuda_fatbin_{d}\"), .first = {d}, .entries = &.{{\n", .{ name, lib_index, first });
        for (entries.items) |e| {
            try out.appendSlice(arena, "        .{ .key = ");
            try appendLiteral(arena, &out, e.key);
            try out.appendSlice(arena, ", .mangled = ");
            try appendLiteral(arena, &out, e.mangled);
            try out.appendSlice(arena, " },\n");
        }
        try out.appendSlice(arena, "    } },\n");
        first += @intCast(entries.items.len);
    }
    try out.print(arena, "}};\n\npub const kernel_count = {d};\n", .{first});

    try cwd.writeFile(io, .{ .sub_path = args[1], .data = out.items });
}

/// Strips the return type and the parameter list from a demangled kernel.
///
/// Parameters:
/// - `demangled`: `cu++filt`'s output for one entry symbol.
///
/// Return: a slice of `demangled`; `error.BadListing` when it does not end
/// in a balanced parameter list.
fn keyOf(demangled: []const u8) ![]const u8 {
    var s = std.mem.trim(u8, demangled, " \r");
    if (std.mem.startsWith(u8, s, "void ")) s = s["void ".len..];
    if (s.len == 0 or s[s.len - 1] != ')') return error.BadListing;
    // Walk back from the closing parenthesis to the one that opens the
    // parameter list; template arguments such as `(int)104` and
    // function-pointer parameters nest inside it.
    var depth: usize = 0;
    var j = s.len;
    while (j > 0) {
        j -= 1;
        switch (s[j]) {
            ')' => depth += 1,
            '(' => {
                depth -= 1;
                if (depth == 0) return std.mem.trimEnd(u8, s[0..j], " ");
            },
            else => {},
        }
    }
    return error.BadListing;
}

/// Appends `s` as a Zig string literal.
///
/// Parameters:
/// - `gpa`: allocator for `out`.
/// - `out`: the buffer being written.
/// - `s`: the text; demangled names hold no control characters, but quotes
///   and backslashes are escaped all the same.
fn appendLiteral(gpa: std.mem.Allocator, out: *std.ArrayList(u8), s: []const u8) !void {
    try out.append(gpa, '"');
    for (s) |ch| {
        if (ch == '"' or ch == '\\') try out.append(gpa, '\\');
        try out.append(gpa, ch);
    }
    try out.append(gpa, '"');
}
